def schedule(T, start):
    d=datetime.date.fromisoformat(start); out=[]
    for name,trades,days in PHASES:
        t=[x for x in trades if x in T and T[x]]
        if not t: continue
        e=d+datetime.timedelta(days=days-1)
        out.append({"phase":name,"trades":", ".join(dict.fromkeys(t)),"start":d.isoformat(),"end":e.isoformat(),"days":days})
        d=e+datetime.timedelta(days=1)
    return out

def dump(T, token=None, **kw):
    token = token or secrets.token_urlsafe(9)
    secs=[]; tot=0
    for k,L in T.items():
        if not L: continue
        lines=[{"item":a,"spec":b,"qty":q,"unit":u,"price":p,"amount":round(q*p)} for a,b,q,u,p in L]
        s=sum(x["amount"] for x in lines); tot+=s
        secs.append({"trade":k,"subtotal":s,"lines":lines})
    d=dict(kw); d["sections"]=secs; d["total"]=tot
    d["codiRate"]=d.get("codiRate") or rate(tot); d["codi"]=round(tot*d["codiRate"])
    n=d["name"]; d["name"]=n[0]+"*"+n[-1] if len(n)>=3 else n[0]+"*"
    json.dump(d, open(os.path.join(OUT, token+".json"),"w"), ensure_ascii=False, indent=1)
    return token, tot, d["codi"]

